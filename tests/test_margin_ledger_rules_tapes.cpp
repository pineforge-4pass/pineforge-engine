/*
 * test_margin_ledger_rules_tapes.cpp -- margin, sizing and admission rules on
 * TradingView's tapes of event-ledger probes.
 *
 * tests/fixtures/margin_ledger_rules holds 381 `lab tv` tapes of 165
 * synthetic probes (README.md there): each probe's script issues a ledger of
 * strategy.entry / strategy.close / strategy.close_all calls at fixed bars --
 * explicit quantities or the default 100 % of equity -- on NYSE:F (15 minutes
 * and 1 day), NASDAQ:AAPL and BINANCE:ETHUSDT.P (15 minutes), at margin 100
 * or 0, with no commission and no slippage. The last entry before the final
 * close_all is the boundary order; an `after_close` probe also issues
 * strategy.close("Seed") right after it. cases.tsv (generated by
 * build_cases.py from each probe's plan.json) lists one row per tape.
 *
 * Each row is replayed through the Pine adapter on every bar of its chart's
 * exported window (bars/, from 00:00 UTC through to 00:00 UTC inclusive): a
 * handwritten host issues the plan's calls on the bar opening at their time,
 * in the script's statement order. Every trade row TradingView reports -- its
 * closed trades and a position still open at the range end, which
 * TradingView lists as a trade closed at the last bar's close -- must be the
 * engine's report row at the same index: side, quantity in lots, entry and
 * exit price in ticks, entry and exit time, and the row count. PnL and the
 * Signal column are not compared. The range-end rows come from the host
 * itself (report_trade_count() / get_report_trade()).
 *
 * The tree ships every margin rule switch
 * (pineforge::source::detail::MarginRuleSwitches) on, which this test
 * checks; the pass runs with the shipped switches. kKnownDivergences names
 * the tapes the engine is known not to reproduce yet: every unlisted tape
 * must match and every listed tape must still differ, so the list shrinks as
 * the engine learns a rule. The two admission halves are then turned off one
 * at a time, and each must cost tapes.
 */

