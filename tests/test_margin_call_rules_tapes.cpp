/*
 * test_margin_call_rules_tapes.cpp -- margin-call, admission and sizing rules
 * on TradingView's own tapes.
 *
 * tests/fixtures/margin_call_rules holds 265 `lab tv` tapes of synthetic
 * probes (README.md there names the families): one market entry -- or a
 * same-bar batch of entries "A", "B", "C" for the two counter controls --
 * placed at a fixed bar and closed with strategy.close_all() at another,
 * optionally behind a ledger of earlier closed trades or reversing an
 * explicit prior long, under a chosen capital, quantity (explicit, 100 % of
 * equity, or the script's floored equity / close), slippage, commission,
 * margin, process_orders_on_close and calc_on_order_fills. cases.tsv
 * (generated by build_cases.py from each tape's parameters.json) lists them
 * one per row. A chart range that ends before the scheduled close_all leaves
 * the position open at the range end.
 *
 * Every one of the 266 tapes is asserted (asserted=1), the 67
 * short-cutoff-gate tapes (a short's margin-call cut-off and slippage gate,
 * MarginScheduleSwitches) included. A tape the fixture marks asserted=0 would
 * be replayed and printed as GAP-MATCH or GAP-DIFF, then replayed with the
 * pooc_fee_sizing switch off and on, its rows checked by nothing; none is.
 *
 * The ten order-controls/ tapes (timed stop entries, strategy.cancel, an
 * SMA-readiness gate, a dynamic strategy.exit stop, a re-entry cooldown) are
 * not in cases.tsv: handwritten hosts make their scripts' strategy.* calls,
 * and each must match like an asserted tape.
 *
 * Each row is replayed through the Pine adapter on every bar of its chart's
 * exported window (bars/, from 00:00 UTC through to 00:00 UTC inclusive) and
 * every trade row TradingView reports -- its closed trades and a position
 * still open at the range end, which TradingView lists as a trade closed at
 * the last bar's close with an empty Signal -- must be the engine's report
 * row at the same index: side, quantity in lots, entry and exit price in
 * ticks, entry and exit time. The range-end rows come from the host itself:
 * PineStrategyHost records a position still open after the last bar as
 * report rows (scheduler_record_range_end, read back through
 * report_trade_count() / get_report_trade()), so nothing is emulated here.
 *
 * kKnownDivergences names the asserted tapes the engine is known not to
 * reproduce yet. Every unlisted asserted tape must match and every listed tape
 * must still differ, so the list shrinks as the engine learns a rule.
 *
 * Each margin rule the adapter implements sits behind its own switch
 * (pineforge::source::detail::MarginRuleSwitches, MarginScheduleSwitches and
 * MarginOpeningSwitches).
 * The tree ships every rule on, which this test checks; it replays the tapes
 * with the shipped switches against kKnownDivergences, turns each rule off
 * alone from there and requires a load-bearing one to cost at least one tape,
 * and turns all of them off to recover the tapes the engine matched before
 * the rules.
 */

