Outcome replay_control(source::PineStrategyHost& host, const Case& c, const std::vector<Bar>& bars) {
    host.run(bars.data(), static_cast<int>(bars.size()), "15", "15");
    Outcome outcome;
    outcome.error = host.last_error();
    for (int index = 0; index < host.report_trade_count(); ++index) {
        const Trade& trade = host.get_report_trade(index);
        outcome.rows.push_back(make_row(trade.is_long, trade.qty, trade.entry_price,
                                        trade.exit_price, trade.entry_time, trade.exit_time, c));
    }
    return outcome;
}

bool same_rows(const Outcome& left, const Outcome& right) {
    if (left.error != right.error || left.rows.size() != right.rows.size()) return false;
    for (std::size_t i = 0; i < left.rows.size(); ++i) {
        const Row& a = left.rows[i];
        const Row& b = right.rows[i];
        if (a.is_long != b.is_long || a.qty_lots != b.qty_lots || a.entry_ticks != b.entry_ticks ||
            a.exit_ticks != b.exit_ticks || a.entry_ms != b.entry_ms || a.exit_ms != b.exit_ms)
            return false;
    }
    return true;
}

// The asserted tapes that match under the current switches.
std::set<std::string> matching_tapes(const std::vector<Case>& cases,
                                     std::map<std::string, std::vector<Bar>>& feeds) {
    std::set<std::string> matched;
    for (const Case& c : cases) {
        if (!c.asserted) continue;
        auto feed = feeds.find(c.bars);
        if (feed == feeds.end()) feed = feeds.emplace(c.bars, load_bars(c.bars)).first;
        if (first_difference(tape_rows(c), replay(c, feed->second)).empty()) matched.insert(c.path);
    }
    return matched;
}

