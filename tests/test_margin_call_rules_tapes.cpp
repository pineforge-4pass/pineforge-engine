// cooldown-atr-entry-clear: the seed short behind a dynamic ATR stop
// re-placed every bar from position_avg_price and the running trough.
class CooldownAtrHost final : public ControlHost {
public:
    CooldownAtrHost(double tick, double step)
        : ControlHost(69001.53831500027, true, true, tick, step) {}
    void on_source_bar(const Bar& bar) override {
        const double position = signed_position_size();
        const int index = pine_bar_index();
        const std::int64_t seed_ms = utc_ms(2026, 1, 8, 19, 45);
        if (bar.timestamp == seed_ms) strategy_entry("seed", false, kNaN, kNaN, 22.186);
        const double volatility = atr(bar);
        if (bar.timestamp == seed_ms) {
            captured_ = volatility;
            trough_ = bar.low;
        }
        if (position < 0.0) {
            trough_ = std::isnan(trough_) ? bar.low : std::min(trough_, bar.low);
            const double working = std::isnan(captured_) ? volatility : captured_;
            const double reference = position_avg_price();
            const double stop = trough_ <= reference - 2.0 * working
                                    ? std::min(reference - 0.1 * working, trough_ + 3.2 * working)
                                    : reference + 2.2 * working;
            strategy_exit("dynamic", "seed", kNaN, stop);
        }
        if (bar.timestamp == utc_ms(2026, 1, 8, 23, 30) && position >= 0.0 &&
            (!observed_ || index - observed_exit_ > 4))
            strategy_entry("candidate", false);
        if (previous_position_ < 0.0 && position == 0.0) {
            observed_ = true;
            observed_exit_ = index;
        }
        if (position == 0.0) {
            captured_ = kNaN;
            trough_ = kNaN;
        }
        if (bar.timestamp == utc_ms(2026, 1, 9, 1, 0)) strategy_close_all();
        previous_position_ = position;
    }

private:
    // ta.atr(14) = ta.rma(true range, 14): the first value the SMA of the
    // first 14 true ranges, then alpha * tr + (1 - alpha) * previous.
    double atr(const Bar& bar) {
        const double range = std::isnan(previous_close_)
                                 ? bar.high - bar.low
                                 : std::max(std::max(bar.high - bar.low,
                                                     std::fabs(bar.high - previous_close_)),
                                            std::fabs(bar.low - previous_close_));
        previous_close_ = bar.close;
        ranges_.push_back(range);
        constexpr std::size_t kLength = 14;
        if (std::isnan(rma_)) {
            if (ranges_.size() >= kLength) {
                double sum = 0.0;
                for (std::size_t i = 0; i < kLength; ++i)
                    sum += ranges_[ranges_.size() - 1 - i] / static_cast<double>(kLength);
                rma_ = sum;
            }
        } else {
            const double alpha = 1.0 / static_cast<double>(kLength);
            rma_ = alpha * range + (1.0 - alpha) * rma_;
        }
        return rma_;
    }
    std::vector<double> ranges_;
    double previous_close_ = kNaN;
    double rma_ = kNaN;
    double captured_ = kNaN;
    double trough_ = kNaN;
    double previous_position_ = kNaN;
    bool observed_ = false;
    int observed_exit_ = 0;
};

