// ta.sma(close, n) over the fed bars: na until n closes, then
// sum(close[i] / n, i = 0 .. n - 1).
class SmaSeries {
public:
    explicit SmaSeries(std::size_t length) : length_(length) {}
    void push(const std::vector<double>& closes) {
        previous_ = current_;
        current_ = kNaN;
        if (closes.size() < length_) return;
        double sum = 0.0;
        for (std::size_t i = 0; i < length_; ++i)
            sum += closes[closes.size() - 1 - i] / static_cast<double>(length_);
        current_ = sum;
    }
    // x > x[1], false when either is na.
    bool rising() const {
        return !std::isnan(current_) && !std::isnan(previous_) && current_ > previous_;
    }

private:
    std::size_t length_;
    double current_ = kNaN;
    double previous_ = kNaN;
};

