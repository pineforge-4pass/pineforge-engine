int main() {
    DualStopSameBarOrderHost host;
    const auto bars = embedded_bars();
    host.run(bars.data(), static_cast<int>(bars.size()));
    CHECK(host.last_error().empty());
    CHECK(host.trade_count() == 5);
    CHECK(near(host.live_position_size(), 0.0));

    // Trade #143: morning SE stop fills first at 2506.06, exits 18:30 at 2529.48
    if (host.trade_count() >= 4) {
        expect_trade("dual-stop#143", host.get_trade(3), false,
                     2506.06, 2529.48, 22.78, 27.88, -23.42);
    }
    // Trade #144: afternoon SE2 stop fills second at 2504.64, exits 18:30 at 2529.48
    if (host.trade_count() >= 5) {
        expect_trade("dual-stop#144", host.get_trade(4), false,
                     2504.64, 2529.48, 21.36, 29.30, -24.84);
    }

    std::printf("test_l10r_dual_stop_same_bar_order: %d passed, %d failed\n", passed, failed);
    return failed == 0 ? 0 : 1;
}
