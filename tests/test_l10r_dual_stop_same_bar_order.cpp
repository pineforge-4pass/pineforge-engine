bool near(double a, double b, double tol = 1e-4) { return std::abs(a - b) < tol; }

Bar mk(std::int64_t t, double o, double h, double l, double c) {
    return {o, h, l, c, 1.0, t};
}

source::PineStrategyConfig cfg(int pyr) {
    source::PineStrategyConfig c;
    c.initial_capital = 1000000;
    c.default_qty_type = static_cast<int>(QtyType::FIXED);
    c.default_qty_value = 1.0;
    c.pyramiding = pyr;
    c.process_orders_on_close = false;
    c.commission_value = 0.0;
    c.slippage = 0;
    return c;
}

void expect_trade(const char* tag, const Trade& t, bool is_long,
                  double entry_px, double exit_px, double fav, double adv,
                  double pnl) {
    std::printf("%s %s @%.4f->%.4f pnl=%.4f mfe=%.4f mae=%.4f "
                "(want @%.4f->%.4f pnl=%.4f mfe=%.4f mae=%.4f)\n",
                tag, is_long ? "L" : "S", t.entry_price, t.exit_price, t.pnl,
                t.max_runup, t.max_drawdown, entry_px, exit_px, pnl, fav, adv);
    CHECK(t.is_long == is_long);
    CHECK(near(t.entry_price, entry_px));
    CHECK(near(t.exit_price, exit_px));
    CHECK(near(t.pnl, pnl));
    CHECK(near(t.max_runup, fav));
    CHECK(near(t.max_drawdown, adv));
}

class DualStopSameBarOrderHost : public source::PineStrategyHost {
public:
    DualStopSameBarOrderHost() {
        configure_pine_strategy(cfg(1));
        set_syminfo_metadata("ETHUSDT", 0.01);
    }

    void on_source_bar(const Bar& bar) override {
        const int hr = pine_hour(bar.timestamp, syminfo_.timezone);
        const int mn = pine_minute(bar.timestamp, syminfo_.timezone);
        if (hr == 2 && mn == 45 && signed_position_size() == 0.0) {
            strategy_entry("LE", true, kNaN, bar.close * 1.002, kNaN, "near long stop");
            strategy_entry("SE", false, kNaN, bar.close * 0.998, kNaN, "near short stop");
        }
        if (signed_position_size() != 0.0 && hr == 6 && mn == 15) {
            strategy_close_all();
        }
        if (hr == 14 && mn == 45 && signed_position_size() == 0.0) {
            strategy_entry("LE2", true, kNaN, bar.close * 1.004, kNaN, "farther long stop");
            strategy_entry("SE2", false, kNaN, bar.close * 0.996, kNaN, "farther short stop");
        }
        if (signed_position_size() != 0.0 && hr == 18 && mn == 15) {
            strategy_close_all();
        }
    }
};

