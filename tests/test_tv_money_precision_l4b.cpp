/*
 * test_tv_money_precision.cpp — TradingView's broker carries money at TEN
 * SIGNIFICANT DIGITS (round 8 family R, OANDA:EURUSD@15; campaign notes
 * log-20260905t164404z-85800609 diagnosis, log-20260905t180248z-0dce5ab0
 * entry-leg admission, log-20260905t180249z-10358e84 margin-call trigger;
 * round 9 follow-up log-20260905t205824z-af397c83 and
 * log-20260905t210117z-ab914192, the whole-order drop band).
 *
 * The consequences pinned and implemented (engine.hpp tv_money_round /
 * tv_money_floor_lot / tv_money_scope, engine_fills.cpp fill-time gate and
 * tv_money_long_margin_call):
 *
 *   sizing      Q = floor_raw( sig10(E_s) / tick(close_S) / step ) x step,
 *               tick(close_S) = ticks x fl(mintick) as the broker holds it
 *   admission   a default 100 %-of-equity, margin-100 MARKET entry is
 *               DROPPED iff E_s < sig10(Q x tick(close_S)); a reversal keeps
 *               only its closing leg; this runs ahead of the exact fill check
 *   whole drop  past that, P = sig10( sig10(E_s) / Q ) < tick(close_S) drops
 *               the WHOLE order (a reversal keeps its position): a decimal tie
 *               at 1e-9 is decided by the ulp of the tick-built price
 *   margin call a margin-100 LONG is liquidated one contract at the first bar
 *               path point p where exact equity <= sig10(|Q| x p)
 *
 * The 203 lab tv capital sweeps of 2025-04-01 (scratch famr-adm-*: flat-{m,p},
 * FL, rev, revb, revc, revd, revL, S1, S1f, S2, S3, pS) are replayed on the
 * registry feed's bars (test_tv_money_precision_data.hpp, generated by
 * gen_tapes_v2.py) and compared ROW FOR ROW — entry bar, side, fill price,
 * quantity, exit bar, exit price, 'Margin call' vs close, net PnL. 202 tapes
 * are asserted (the 52 band tapes revb b06..b28, revd00..03, revL L24..L33,
 * S100..S103, S307..S317 among them); the 1 the generator's independent
 * predictor does not explain is the documented residual (revL L23: TV's
 * one-unit entry fill when the entry leg fails with Q == |position| + 1.00)
 * and is replayed for information only — it must never be silently
 * promoted. test_tv_money_band.cpp replays the famr3 sweeps that pinned the
 * band on other bars.
 */

