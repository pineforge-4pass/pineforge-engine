static void test_money_round() {
    std::printf("-- tv_money_round: ten significant digits, half-up --\n");
    CHECK(near(tv_money_round(998763.3420503), 998763.3421, 1e-12));
    CHECK(near(tv_money_round(998763.3420484), 998763.3420, 1e-12));
    CHECK(near(tv_money_round(998763.3425504), 998763.3426, 1e-12));
    CHECK(near(tv_money_round(998763.3425483), 998763.3425, 1e-12));
    CHECK(near(tv_money_round(1000000.0015396), 1000000.002, 1e-12));
    CHECK(near(tv_money_round(1000000.0014996), 1000000.001, 1e-12));
    CHECK(near(tv_money_round(1001239.6645078), 1001239.665, 1e-12));
    CHECK(near(tv_money_round(1001239.6644978), 1001239.664, 1e-12));
    CHECK(near(tv_money_round(948825.1787804), 948825.1788, 1e-12));
    CHECK(near(tv_money_round(948825.1787404), 948825.1787, 1e-12));
    CHECK(near(tv_money_round(-1234.4350144), -1234.435014, 1e-12));
    CHECK(tv_money_round(0.0) == 0.0);
}

// Every famr-adm tape, row for row, on the registry bars.
static void test_tape_replays() {
    std::printf("-- famr-adm-* capital sweeps: row-for-row replay on the 2025-04-01 bars --\n");
    const std::vector<Bar> bars = tape_bars();
    CHECK(bars.size() >= 17);
    int asserted = 0, asserted_ok = 0, residual = 0, residual_match = 0;
    std::vector<std::string> failed;
    for (const Tape& t : kTapes) {
        SweepProbe eng(t.capital, t.signals, t.n_signals);
        eng.run(bars.data(), bars.size());
        const std::vector<Row> got = eng.rows();
        const std::vector<Row> want = tape_rows(t);
        if (t.expect_match) {
            ++asserted;
            const int mm = rows_mismatch(got, want, /*verbose=*/true);
            if (mm == 0) ++asserted_ok; else failed.push_back(t.name);
            if (mm != 0) std::printf("   %s: %d row mismatch(es)\n", t.name, mm);
        } else {
            ++residual;
            const int mm = rows_mismatch(got, want, /*verbose=*/false);
            if (mm == 0) ++residual_match;
        }
    }
    std::printf("   asserted %d/%d tapes replay row for row; residual %d (%d happen to match): %s\n",
                asserted_ok, asserted, residual, residual_match,
                "the one-unit entry fill, not implemented");
    for (const std::string& f : failed) std::printf("   FAILED tape: %s\n", f.c_str());
    CHECK(asserted == 202);
    CHECK(asserted_ok == asserted);
    CHECK(residual == 1);
}

// Named pins on top of the replay (the rules stated on the numbers).
static void test_named_pins() {
    std::printf("-- named pins --\n");
    const std::vector<Bar> bars = tape_bars();
    auto find = [](const char* name) -> const Tape* {
        for (const Tape& t : kTapes) if (std::strcmp(t.name, name) == 0) return &t;
        return nullptr;
    };
    auto first_entry_qty = [&](const char* name, int64_t fill_ts) -> double {
        const Tape* t = find(name);
        if (t == nullptr) return -1.0;
        SweepProbe eng(t->capital, t->signals, t->n_signals);
        eng.run(bars.data(), bars.size());
        double q = 0.0;
        for (const Row& r : eng.rows()) if (r.entry_ts == fill_ts) q += r.qty;
        return q;
    };
    const int64_t fill1 = kBars[2].ts;   // 08:30Z open
    const int64_t fill2 = kBars[6].ts;   // 09:30Z open
    // Sizing from the ROUNDED equity: revc03 sizes the exact floor, revc04
    // (E 2e-6 higher, past the half unit) one lot more — which then fails the
    // rounded-cost admission, so its entry leg is dropped and only the close
    // leg fills (the tape).
    CHECK(near(first_entry_qty("famr-adm-revc-revc03", fill2), 922832.66, 1e-6));
    CHECK(near(first_entry_qty("famr-adm-revc-revc04", fill2), 0.0, 1e-6));
    // S2: the rounded equity lands one lot BELOW the exact floor.
    CHECK(near(first_entry_qty("famr-adm-S206", fill2), 925601.16, 1e-6));
    CHECK(near(first_entry_qty("famr-adm-S209", fill2), 925601.17, 1e-6));
    // Bare capital vs the rounded cost 1000000.002 (925120.73 x 1.08094).
    CHECK(near(first_entry_qty("famr-adm-revL-L05", fill1), 925120.72, 1e-6));  // C .0014996 -> .72
    CHECK(near(first_entry_qty("famr-adm-revL-L06", fill1), 0.0, 1e-6));        // .0015396 -> .73, dropped
    CHECK(near(first_entry_qty("famr-adm-revL-L17", fill1), 0.0, 1e-6));        // .0019796 dropped
    CHECK(near(first_entry_qty("famr-adm-FL02", fill1), 0.0, 1e-6));            // .0019980 dropped
    CHECK(near(first_entry_qty("famr-adm-revL-L18", fill1), 925120.73, 1e-6));  // .0020196 admitted
    CHECK(near(first_entry_qty("famr-adm-flat-p0000", fill1), 925000.0, 1e-6)); // C == cost: admitted
    // The one-contract margin call on a long in profit, at the first path
    // point where the exact equity is <= the rounded position value.
    {
        const Tape* t = find("famr-adm-revL-L18");
        SweepProbe eng(t->capital, t->signals, t->n_signals);
        eng.run(bars.data(), bars.size());
        bool one_unit_at_high = false;
        for (const Row& r : eng.rows()) {
            if (r.kind == 1 && r.is_long && near(r.qty, 1.0, 1e-9)
                && r.exit_ts == kBars[2].ts && near(r.exit_price, 1.08151, 1e-9)) {
                one_unit_at_high = true;
            }
        }
        CHECK(one_unit_at_high);
    }
    {
        const Tape* t = find("famr-adm-revL-L26");
        SweepProbe eng(t->capital, t->signals, t->n_signals);
        eng.run(bars.data(), bars.size());
        int long_margin_calls = 0;
        for (const Row& r : eng.rows()) if (r.kind == 1 && r.is_long) ++long_margin_calls;
        CHECK(long_margin_calls == 0);   // cash 0.00045 > every residual
    }
    // The whole-order drop band (rule 5): the long -> short reversal at the
    // 09:30Z open is dropped ENTIRELY — no short fills and the long is NOT
    // closed there (it runs to the close_all) — when sig10(sig10(E_s)/Q)
    // ties the sizing close as a decimal and the tick-built price sits one
    // ulp above double(close). revb b04/b05 just below the band are
    // close-only (the position exits at 09:30Z, no new entry), revb b06
    // opens the band, S100 is the 7-digit tie, revL L26 / S317 sit inside.
    auto second_decision = [&](const char* name) -> std::string {
        const Tape* t = find(name);
        if (t == nullptr) return "missing";
        SweepProbe eng(t->capital, t->signals, t->n_signals);
        eng.run(bars.data(), bars.size());
        // Side-agnostic: revb/S3 open short and reverse long, S1/revL/revd
        // open long and reverse short.
        double entry_qty = 0.0; bool position_exits_at_fill2 = false;
        for (const Row& r : eng.rows()) {
            if (r.entry_ts == fill2) entry_qty += r.qty;
            if (r.entry_ts < fill2 && r.exit_ts == fill2 && r.kind == 0) position_exits_at_fill2 = true;
        }
        if (entry_qty > 1.5) return "admit";
        if (entry_qty > 0.0) return "one-unit";
        return position_exits_at_fill2 ? "close-only" : "whole-drop";
    };
    CHECK(second_decision("famr-adm-revb-b05") == "close-only");
    CHECK(second_decision("famr-adm-revb-b06") == "whole-drop");
    CHECK(second_decision("famr-adm-revb-b28") == "whole-drop");
    CHECK(second_decision("famr-adm-S100") == "whole-drop");
    CHECK(second_decision("famr-adm-S103") == "whole-drop");
    CHECK(second_decision("famr-adm-revL-L26") == "whole-drop");
    CHECK(second_decision("famr-adm-revL-L33") == "whole-drop");
    CHECK(second_decision("famr-adm-S317") == "whole-drop");
    // tv_money_floor_lot: the everybar 1.085 placement — sig10(E) / tick(1.085)
    // = 918062.29999999992 floors to 918062.29 (TV filled 33222 + 884840.29),
    // where the nudged apply_qty_step would say 918062.30.
    {
        const double tick_1085 = std::floor(1.085 / 0.00001 + 0.5) * 0.00001;
        CHECK(tick_1085 > 1.085);   // fl(1e-5) carries the price one ulp up
        const double q = tv_money_round(996097.5955029) / tick_1085;
        CHECK(near(tv_money_floor_lot(q, 0.01), 918062.29, 1e-9));
        CHECK(near(std::floor(q / 0.01 + 1e-6) * 0.01, 918062.30, 1e-9));
    }
}

// Integer-lot / continuous instruments keep the exact arithmetic (scope).
static void test_out_of_scope_untouched() {
    std::printf("-- integer-lot / continuous instruments keep the exact arithmetic --\n");
    Signal sig[] = {{600000LL, 1}};
    std::vector<Bar> b;
    for (int i = 0; i < 3; ++i) {
        Bar bar; bar.open = bar.high = bar.low = bar.close = 100.0;
        bar.volume = 1.0; bar.timestamp = 600000LL * (i + 1);
        b.push_back(bar);
    }
    {
        SweepProbe p(10000.0015396, sig, 1);
        p.set_step(1.0);
        p.set_syminfo_mintick(0.01);
        p.run(b.data(), b.size());
        CHECK(near(p.signed_position_size(), 100.0, 1e-9));
    }
    {
        SweepProbe q(10000.0015396, sig, 1);
        q.set_step(0.0);
        q.set_syminfo_mintick(0.01);
        q.run(b.data(), b.size());
        CHECK(near(q.signed_position_size(), 100.000015396, 1e-9));
    }
}

