source::PineStrategyConfig cfg(double capital) {
    source::PineStrategyConfig c;
    c.initial_capital = capital;
    c.default_qty_type = static_cast<int>(QtyType::FIXED);
    c.default_qty_value = 1.0;
    c.pyramiding = 0;
    c.process_orders_on_close = false;
    c.calc_on_order_fills = false;
    c.commission_value = 0.0;
    c.slippage = 0;
    c.margin_long = 100.0;
    c.margin_short = 100.0;
    return c;
}

class OwnerBreakout : public source::PineStrategyHost {
public:
    OwnerBreakout()
        : source::PineStrategyHost(),
          long_qty_(0.0) {
        configure_pine_strategy(cfg(10201.4612078724));
        set_syminfo_metadata("ETHUSDT", 0.01);
    }

    void on_source_bar(const Bar& bar) override {
        switch (bar.timestamp) {
        case 1747349100000LL:  // 2025-05-15 22:45 signal
            strategy_entry("Short Breakout", false, kNaN, 2540.17,
                           3.74010944);
            break;
        case 1747350000000LL:  // 23:00 stop-entry fill
            if (signed_position_size() < 0.0)
                strategy_exit("Exit Short", "Short Breakout", kNaN, 2646.10);
            break;
        case 1747395900000LL:  // post-cycle EOD close_all
            strategy_close_all();
            break;
        case 1747699200000LL:  // 2025-05-20 00:00 signal
            long_qty_ = current_equity() / 2546.97;
            strategy_entry("Long Breakout", true, kNaN, 2546.97, long_qty_);
            break;
        case 1747700100000LL:  // 00:15 full-margin stop-entry fill
            if (signed_position_size() > 0.0) {
                strategy_exit("Exit Long", "Long Breakout", kNaN, 2312.62);
                strategy_cancel("Short Breakout");
            }
            break;
        case 1747774800000LL:  // 21:00 EOD signal
            if (signed_position_size() > 0.0)
                strategy_close_all();
            break;
        case 1748133000000LL:  // 2025-05-25 00:30 signal
            strategy_entry("Short Breakout", false, kNaN, 2494.79,
                           0.06533652);
            break;
        case 1748133900000LL:  // 00:45 stop-entry fill
            if (signed_position_size() < 0.0)
                strategy_exit("Exit Short", "Short Breakout", kNaN, 2508.30);
            break;
        default:
            break;
        }
    }

    double long_qty() const { return long_qty_; }

private:
    double long_qty_;
};

void expect_trade(int row, const Trade& t, bool is_long,
                  std::int64_t entry_time, double entry_price,
                  std::int64_t exit_time, double exit_price, double qty,
                  double pnl, double runup, double drawdown) {
    std::printf("#%d %s entry=%lld %.8f exit=%lld %.8f qty=%.8f pnl=%.8f mfe=%.8f mae=%.8f\n",
                row, is_long ? "long" : "short",
                static_cast<long long>(t.entry_time), t.entry_price,
                static_cast<long long>(t.exit_time), t.exit_price, t.qty,
                t.pnl, t.max_runup, -t.max_drawdown);
    CHECK(t.is_long == is_long);
    CHECK(t.entry_time == entry_time);
    CHECK(near(t.entry_price, entry_price));
    CHECK(t.exit_time == exit_time);
    CHECK(near(t.exit_price, exit_price));
    CHECK(near(t.qty, qty));
    CHECK(near(t.pnl, pnl));
    CHECK(near(t.max_runup, runup, 1e-5));
    CHECK(near(-t.max_drawdown, drawdown, 1e-5));
}

