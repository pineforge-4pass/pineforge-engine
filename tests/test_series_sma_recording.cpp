int main() {
    constexpr double sources[] = {1e16, 1, 1e-16, -1e16, -1};
    pineforge::source::SeriesSma sma;
    int failures = 0;
    for (int t = 1994643 - 60; t <= last; ++t) {
        const int block = (t / 24) % 3;
        const int length = block == 1 ? (t % 2 == 0 ? 5 : 3) : block == 2 ? 7 : 5;
        const double got = sma.compute(sources[t % 5], length);
        if (t >= first && std::memcmp(&got, &expected[t - first], sizeof got) != 0) {
            std::printf("FAIL t=%d length=%d got=%.17g expected=%.17g\n",
                        t, length, got, expected[t - first]);
            ++failures;
        }
    }
    if (failures) return 1;
    std::printf("PASS t=%d..%d: %zu consecutive SMA values\n", first, last, std::size(expected));
    return 0;
}
