// Integer tick index of a 2-dp price string, parsed digit-by-digit so the
// expectation never goes through floating point.
long long cents_of(const char* s) {
    long long whole = 0, frac = 0;
    int nfrac = 0;
    const char* p = s;
    for (; *p && *p != '.'; ++p) whole = whole * 10 + (*p - '0');
    if (*p == '.') {
        for (++p; *p; ++p) { frac = frac * 10 + (*p - '0'); ++nfrac; }
    }
    while (nfrac < 2) { frac *= 10; ++nfrac; }
    return whole * 100 + frac;
}
