class TickEngine : public BacktestEngine {
public:
    TickEngine() {
        initial_capital_ = 1'000'000;
        default_qty_type_ = QtyType::FIXED;
        default_qty_value_ = 1.0;
        slippage_ = 0;
        commission_value_ = 0;
        pyramiding_ = 1;
        syminfo_mintick_ = 0.01;
    }
};

// 2. process_orders_on_close: long entry at a half-cent close that rounds
//    DOWN (228.765 -> 228.76; old buy-ceil: 228.77), close at a half-cent
//    close that rounds UP (214.385 -> 214.39; old sell-floor: 214.38).
class PoocLong : public TickEngine {
public:
    PoocLong() { process_orders_on_close_ = true; }
    void on_bar(const Bar&) override {
        if (bar_index_ == 1) strategy_entry("L", true, kNaN, kNaN, 1.0, "long");
        if (bar_index_ == 3) strategy_close("L", "close");
    }
};

static void test_pooc_market_fills_nearest_tick() {
    std::printf("test_pooc_market_fills_nearest_tick\n");
    PoocLong p;
    Bar bars[5] = {
        {228.50, 228.90, 228.30, 228.60, 1000, kT0 + 0 * k15m},
        {228.60, 228.90, 228.30, 228.765, 1000, kT0 + 1 * k15m},  // entry @ close
        {228.70, 229.00, 228.20, 228.50, 1000, kT0 + 2 * k15m},
        {228.50, 228.60, 214.00, 214.385, 1000, kT0 + 3 * k15m},  // exit @ close
        {214.40, 214.60, 214.20, 214.50, 1000, kT0 + 4 * k15m},
    };
    p.run(bars, 5);
    CHECK(p.trade_count() == 1);
    if (p.trade_count() == 1) {
        CHECK(near(p.get_trade(0).entry_price, 228.76));
        CHECK(near(p.get_trade(0).exit_price, 214.39));
    }
}

