// Exposes the protected rounding helpers on a 0.01-tick symbol.
class RoundingProbe : public BacktestEngine {
public:
    RoundingProbe() { syminfo_mintick_ = 0.01; }
    void on_bar(const Bar&) override {}
    double nearest(double p) const { return round_to_mintick(p); }
    double bar_fill(double p) const { return bar_fill_price(p); }
    double directional(double p, bool up) const {
        return round_to_mintick_directional(p, up);
    }
    double slipped(double p, bool is_buy) const { return apply_slippage(p, is_buy); }
};

// ─────────────────────────────────────────────────────────────────────
// 1. Census replay. For every pair the engine's nearest-tick helper must
//    land on TV's fill: bit-for-bit on the tick index (the integer that
//    floor(raw / 0.01 + 0.5) produces equals the fill's cents), and within
//    1e-9 / at 2 dp on the double it books. bar_fill_price is the same
//    function. The directional snap is asserted to DISAGREE on the down
//    cases for a buy and on the up cases for a sell — the finding-432/446
//    defect this test pins.
// ─────────────────────────────────────────────────────────────────────
static void replay(const CensusPair* rows, size_t n, const char* name,
                   bool expect_down) {
    RoundingProbe e;
    int mismatch = 0;
    for (size_t i = 0; i < n; ++i) {
        const double raw = std::strtod(rows[i].raw_close, nullptr);
        const long long want_cents = cents_of(rows[i].tv_fill);
        const double got = e.nearest(raw);
        // Tick index, bit-for-bit.
        const long long got_cents =
            static_cast<long long>(std::floor(raw / 0.01 + 0.5));
        const bool ok_idx = got_cents == want_cents;
        // Booked double.
        char buf[32];
        std::snprintf(buf, sizeof buf, "%.2f", got);
        const bool ok_dbl = near(got, std::strtod(rows[i].tv_fill, nullptr))
                            && cents_of(buf) == want_cents
                            && got == e.bar_fill(raw);
        if (!ok_idx || !ok_dbl) {
            ++mismatch;
            if (mismatch <= 5) {
                std::fprintf(stderr, "  %s: raw %s -> engine %.17g (%s) want %s\n",
                             name, rows[i].raw_close, got, buf, rows[i].tv_fill);
            }
        }
        // Midpoint classification: down rows sit just under the midpoint,
        // up rows on or above it.
        const double r = raw / 0.01;
        const double frac = r - std::floor(r);
        CHECK(expect_down ? (frac < 0.5) : (frac >= 0.5));
        // The directional snap gets the adverse side wrong on the discriminating
        // side: a buy ceils a down case, a sell floors an up case.
        if (expect_down) {
            CHECK(!near(e.directional(raw, /*is_long_stop=*/true), got));
            CHECK(!near(e.slipped(raw, /*is_buy=*/true), got));
        } else {
            CHECK(!near(e.directional(raw, /*is_long_stop=*/false), got));
            CHECK(!near(e.slipped(raw, /*is_buy=*/false), got));
        }
        // Once nearest-rounded, the downstream directional snap is an identity
        // in both directions (slippage 0) — this is what lets bar_fill_price
        // sit in front of apply_slippage at every raw-bar-price call site.
        CHECK(e.slipped(got, true) == got);
        CHECK(e.slipped(got, false) == got);
    }
    std::printf("  %s: %zu pairs, %d mismatch\n", name, n, mismatch);
    CHECK(mismatch == 0);
}

static void test_census_replay() {
    std::printf("test_census_replay\n");
    replay(kMidpointDown, sizeof kMidpointDown / sizeof kMidpointDown[0],
           "midpoint-down", /*expect_down=*/true);
    replay(kMidpointUp, sizeof kMidpointUp / sizeof kMidpointUp[0],
           "midpoint-up", /*expect_down=*/false);
    // 4-dp prints: not midpoints, plain nearest.
    RoundingProbe e;
    for (const CensusPair& p : kFourDp) {
        const double raw = std::strtod(p.raw_close, nullptr);
        CHECK(near(e.nearest(raw), std::strtod(p.tv_fill, nullptr)));
        CHECK(static_cast<long long>(std::floor(raw / 0.01 + 0.5)) == cents_of(p.tv_fill));
    }
    // The exemplars, spelled out.
    CHECK(near(e.nearest(228.765), 228.76));  // 22876.499999999996 -> down
    CHECK(near(e.nearest(214.385), 214.39));  // 21438.5 -> up
    // NaN / no-tick passthrough.
    CHECK(std::isnan(e.nearest(kNaN)));
    // On-grid prices are fixed points (ETH-style feed: no behavioural change).
    for (double p : {1803.12, 1803.13, 2000.00, 0.01, 100.5}) {
        CHECK(near(e.nearest(p), p));
        CHECK(e.slipped(e.nearest(p), true) == e.slipped(p, true));
        CHECK(e.slipped(e.nearest(p), false) == e.slipped(p, false));
    }
}

// ─────────────────────────────────────────────────────────────────────
// End-to-end: market fills on a 0.01-tick symbol whose bar prices carry
