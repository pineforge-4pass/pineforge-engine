#!/usr/bin/env python3
"""Synthetic default-ALL collector tests; never real-host or hosted-build proof.

Run only off-master. CLI fixtures stay in .lane-notes/scratch and are retained.
No subprocesses, Make evaluation, source discovery, or embedded file follows.
"""
from __future__ import annotations

import contextlib
import copy
import hashlib
import io
import json
from pathlib import Path
import unittest
from unittest import mock
import uuid

import clang_build_shards as shards


HEAD = '1' * 40
TREE = '2' * 40
SCRATCH = Path(__file__).resolve().parents[1] / '.lane-notes' / 'scratch'
HEADER = ('# CMAKE generated file: DO NOT EDIT!\n'
          '# Generated by "Unix Makefiles" Generator, CMake Version 3.28\n')


def fixture():
    """Tiny generated-shape graph: one excluded target is a required dependency."""
    directories = [
        {'build': '.', 'source': '.', 'childIndexes': [1],
         'targetIndexes': [0], 'projectIndex': 0},
        {'build': 'tests', 'source': 'tests', 'parentIndex': 0,
         'childIndexes': [2], 'targetIndexes': [1, 2, 3], 'projectIndex': 0},
        {'build': 'tests/deep', 'source': 'tests/deep', 'parentIndex': 1,
         'targetIndexes': [4], 'projectIndex': 0},
    ]
    targets = [
        {'name': name, 'id': name + '::@synthetic', 'directoryIndex': directory,
         'projectIndex': 0, 'jsonFile': 'target-' + name + '.json'}
        for name, directory in [('engine', 0), ('runner', 1), ('needed', 1),
                                ('opt_in', 1), ('leaf', 2)]
    ]
    model = {
        'kind': 'codemodel', 'version': {'major': 2, 'minor': 6},
        'paths': {'source': '/synthetic/source', 'build': '/synthetic/build'},
        'configurations': [{
            'name': 'Release', 'directories': directories, 'targets': targets,
            'projects': [{'name': 'Synthetic', 'directoryIndexes': [0, 1, 2],
                          'targetIndexes': [0, 1, 2, 3, 4]}],
        }],
    }
    rules = (
        '.SUFFIXES:\n% : %,v\n% : RCS/%\n% : RCS/%,v\n'
        '% : SCCS/s.%\n% : s.%\n.SUFFIXES: .hpux_make_needs_suffix_list\n'
        '$(VERBOSE)MAKESILENT = -s\n$(VERBOSE).SILENT:\n'
        'SHELL = /bin/sh\nCMAKE_COMMAND = /usr/bin/cmake\n'
        'RM = /usr/bin/cmake -E rm -f\nEQUALS = =\n'
        'CMAKE_SOURCE_DIR = /synthetic/source\nCMAKE_BINARY_DIR = /synthetic/build\n'
        'default_target: all\n.PHONY : default_target\n'
        'all: CMakeFiles/engine.dir/all\nall: tests/all\n.PHONY : all\n'
        'tests/all: tests/CMakeFiles/runner.dir/all\n'
        'tests/all: tests/deep/all\n.PHONY : tests/all\n'
        'tests/deep/all: tests/deep/CMakeFiles/leaf.dir/all\n'
        '.PHONY : tests/deep/all\n'
        'CMakeFiles/engine.dir/all:\n'
        '\t$(MAKE) -f CMakeFiles/engine.dir/build.make\n'
        '.PHONY : CMakeFiles/engine.dir/all\n'
        'tests/CMakeFiles/runner.dir/all: tests/CMakeFiles/needed.dir/all\n'
        'tests/CMakeFiles/needed.dir/all:\n'
        'tests/deep/CMakeFiles/leaf.dir/all:\n'
        'tests/CMakeFiles/opt_in.dir/all:\n'
        '.PHONY : tests/CMakeFiles/opt_in.dir/all\n'
    )
    return HEADER + rules, model


def encoded(model):
    return json.dumps(model, sort_keys=True).encode('utf-8')


def collect(text=None, model=None, **overrides):
    default_text, default_model = fixture()
    arguments = dict(configuration='Release', head=HEAD, tree=TREE,
                     architecture='synthetic-arm64')
    arguments.update(overrides)
    return shards.collect_inventory(
        (default_text if text is None else text).encode('utf-8'),
        encoded(default_model if model is None else model), **arguments)


class InventoryReachabilityTests(unittest.TestCase):
    def test_nested_default_closure_includes_required_excluded_target(self):
        result = collect()
        self.assertEqual(result['schema'], 'clang-build-inventory-v1')
        self.assertEqual(result['targets'], ['engine', 'leaf', 'needed', 'runner'])
        self.assertEqual(result['provenance']['reachable_all_nodes'], [
            'CMakeFiles/engine.dir/all', 'all', 'tests/CMakeFiles/needed.dir/all',
            'tests/CMakeFiles/runner.dir/all', 'tests/all',
            'tests/deep/CMakeFiles/leaf.dir/all', 'tests/deep/all'])
        self.assertEqual(result['provenance']['excluded_registered_targets'], ['opt_in'])
        binding = {row['name']: row for row in result['provenance']['target_bindings']}
        self.assertEqual(binding['leaf']['build'], 'tests/deep')
        self.assertEqual(binding['leaf']['id'], 'leaf::@synthetic')

    def test_root_all_exact_set_changes_even_when_count_stays_equal(self):
        text, model = fixture()
        changed = text.replace('all: CMakeFiles/engine.dir/all\n',
                               'all: tests/CMakeFiles/opt_in.dir/all\n', 1)
        before, after = collect(text, model), collect(changed, model)
        self.assertEqual(len(before['targets']), len(after['targets']))
        self.assertEqual(after['targets'], ['leaf', 'needed', 'opt_in', 'runner'])
        self.assertNotEqual(before['targets'], after['targets'])
        self.assertEqual(after['provenance']['excluded_registered_targets'], ['engine'])

    def test_registered_exclusion_is_reachability_not_a_name_policy(self):
        text, model = fixture()
        result = collect(text + 'all: tests/CMakeFiles/opt_in.dir/all\n', model)
        self.assertEqual(result['targets'], ['engine', 'leaf', 'needed', 'opt_in', 'runner'])
        self.assertEqual(result['provenance']['excluded_registered_targets'], [])

    def test_unreachable_directory_alias_does_not_expand_registered_population(self):
        text, model = fixture()
        changed = text.replace('all: tests/all\n', '', 1)
        result = collect(changed, model)
        self.assertEqual(result['targets'], ['engine'])
        self.assertEqual(result['provenance']['excluded_registered_targets'],
                         ['leaf', 'needed', 'opt_in', 'runner'])

    def test_repeated_rules_continuations_and_duplicate_edges_are_additive(self):
        text, model = fixture()
        changed = text.replace('all: CMakeFiles/engine.dir/all\nall: tests/all\n',
                               'all: CMakeFiles/engine.dir/all ' + '\\' + '\n' +
                               '  tests/all\nall: tests/all\n')
        changed += 'tests/CMakeFiles/runner.dir/all: CMakeFiles/engine.dir/all\n'
        result = collect(changed, model)
        self.assertEqual(result['targets'], collect()['targets'])
        self.assertEqual(len(result['provenance']['reachable_all_nodes']), 7)

    def test_recipes_comments_and_unreachable_non_all_rules_add_no_edges(self):
        text, model = fixture()
        changed = text + (
            '# Synthetic comment: 合成\n\t@echo 合成\n'
            '# all: tests/CMakeFiles/opt_in.dir/all\n'
            'clean: $(UNKNOWN) | arbitrary ; never execute\n'
            'preinstall: missing\nfast: missing\n'
            '\t$(shell never-execute) ' + '\\' + '\n' +
            'all: tests/CMakeFiles/opt_in.dir/all\n'
            'all: tests/all ; $(shell never-execute)\n'
            'all: tests/all # tests/CMakeFiles/opt_in.dir/all\n'
            '.PHONY : tests/CMakeFiles/opt_in.dir/all\n')
        self.assertEqual(collect(changed, model)['targets'], collect()['targets'])

    def test_shared_dependency_dag_is_not_a_cycle(self):
        text, model = fixture()
        text += 'tests/deep/CMakeFiles/leaf.dir/all: tests/CMakeFiles/needed.dir/all\n'
        self.assertEqual(collect(text, model)['targets'], collect()['targets'])

    def test_input_hashes_configuration_and_caller_claims_are_recorded(self):
        text, model = fixture()
        result = collect(text, model)
        self.assertEqual((result['head'], result['tree']), (HEAD, TREE))
        provenance = result['provenance']
        self.assertEqual(provenance['inputs'], {
            'makefile2': {'sha256': hashlib.sha256(text.encode()).hexdigest()},
            'codemodel': {'sha256': hashlib.sha256(encoded(model)).hexdigest()},
        })
        self.assertEqual(provenance['configuration'], 'Release')
        self.assertEqual(provenance['generator'], 'Unix Makefiles')
        self.assertEqual(provenance['architecture'], 'synthetic-arm64')
        self.assertIn('caller-supplied', provenance['identity_semantics'])
        changed = collect(text + '# byte identity changes\n', model,
                          head='3' * 40, tree='4' * 40, architecture='synthetic-x86_64')
        self.assertEqual(changed['targets'], result['targets'])
        self.assertNotEqual(changed['provenance']['inputs'], provenance['inputs'])
        self.assertEqual(changed['head'], '3' * 40)
        self.assertEqual(changed['provenance']['architecture'], 'synthetic-x86_64')

    def test_exact_configuration_is_selected_instead_of_unioning_models(self):
        text, model = fixture()
        debug = copy.deepcopy(model['configurations'][0])
        debug['name'] = 'Debug'
        debug['targets'][0]['name'] = 'debug_engine'
        debug['targets'][0]['id'] = 'debug_engine::@synthetic'
        model['configurations'].insert(0, debug)
        self.assertEqual(collect(text, model)['targets'], collect()['targets'])
        with self.assertRaises(shards.EvidenceError):
            collect(text, model, configuration='RelWithDebInfo')


class InventoryRefusalTests(unittest.TestCase):
    def test_missing_root_and_missing_reachable_rule_are_refused(self):
        text, model = fixture()
        for changed in (
                text.replace('all: CMakeFiles/engine.dir/all\nall: tests/all\n', ''),
                text.replace('tests/CMakeFiles/needed.dir/all:\n', ''),
                text + 'all: tests/missing/all\n'):
            with self.subTest(changed=changed), self.assertRaises(shards.EvidenceError):
                collect(changed, model)

    def test_reachable_non_all_node_is_refused_even_if_it_has_a_rule(self):
        text, model = fixture()
        with self.assertRaises(shards.EvidenceError):
            collect(text + 'all: clean\nclean:\n', model)

    def test_reachable_unregistered_concrete_target_is_refused(self):
        text, model = fixture()
        with self.assertRaises(shards.EvidenceError):
            collect(text + 'all: CMakeFiles/unknown.dir/all\n'
                    'CMakeFiles/unknown.dir/all:\n', model)

    def test_same_registered_name_in_wrong_build_directory_is_refused(self):
        text, model = fixture()
        changed = text.replace('CMakeFiles/engine.dir/all',
                               'tests/CMakeFiles/engine.dir/all')
        with self.assertRaisesRegex(shards.EvidenceError, 'unknown or unregistered reachable'):
            collect(changed, model)

    def test_cycles_in_aliases_and_concrete_prerequisites_are_refused(self):
        text, model = fixture()
        for edge in ('tests/deep/all: all\n',
                     'tests/CMakeFiles/needed.dir/all: tests/CMakeFiles/runner.dir/all\n'):
            with self.subTest(edge=edge), self.assertRaisesRegex(shards.EvidenceError, 'cycle'):
                collect(text + edge, model)

    def test_reachable_variables_escapes_and_unsupported_edges_are_refused(self):
        text, model = fixture()
        for edge in ('$(TARGET)', '${TARGET}', r'tests\ /all', r'tests\/all',
                     r'tests/all\#hidden', 'tests/all | CMakeFiles/engine.dir/all',
                     'tests/%/all', 'tests/../tests/all', './tests/all',
                     'tests//all', '/tests/all', 'tests/all: another'):
            with self.subTest(edge=edge), self.assertRaises(shards.EvidenceError):
                collect(text + 'all: ' + edge + '\n', model)

    def test_unsupported_rule_grammar_and_global_directives_are_not_skipped(self):
        text, model = fixture()
        for line in ('all:: tests/all', 'all &: tests/all', 'all tests/all: tests/all',
                     'all tests/all', 'all = tests/all', '$(TARGET): tests/all',
                     'include other.mk', '-include other.mk', 'sinclude other.mk',
                     'ifeq (a,b)', 'define RULE', '$(eval all: tests/all)',
                     '.RECIPEPREFIX = >', '.POSIX:', '.SECONDEXPANSION:',
                     '.ONESHELL:', 'all: tests/all \\'):
            with self.subTest(line=line), self.assertRaises(shards.EvidenceError):
                collect(text + line + '\n', model)

    def test_nonstandard_line_separators_and_bare_carriage_returns_are_refused(self):
        text, model = fixture()
        for separator in ('\r', '\x85', '\u2028'):
            with self.subTest(separator=separator), self.assertRaises(shards.EvidenceError):
                collect(text + '# comment' + separator +
                        'all: tests/CMakeFiles/opt_in.dir/all\n', model)

    def test_generator_and_generated_header_are_required(self):
        text, model = fixture()
        for changed in (text.replace('Unix Makefiles', 'Ninja'),
                        text.replace('# CMAKE generated file: DO NOT EDIT!\n', ''),
                        text + HEADER):
            with self.subTest(changed=changed), self.assertRaises(shards.EvidenceError):
                collect(changed, model)

    def test_empty_default_target_population_is_refused(self):
        _, model = fixture()
        with self.assertRaises(shards.EvidenceError):
            collect(HEADER + 'all:\n.PHONY : all\n', model)

    def test_unique_target_names_ids_and_reference_names_are_required(self):
        text, model = fixture()
        for key in ('name', 'id', 'jsonFile'):
            changed = copy.deepcopy(model)
            targets = changed['configurations'][0]['targets']
            targets[1][key] = targets[0][key]
            with self.subTest(key=key), self.assertRaises(shards.EvidenceError):
                collect(text, changed)

    def test_directory_target_indexes_must_match_in_both_directions(self):
        text, model = fixture()
        for indexes in ([], [0, 0], [1], [99], [True]):
            changed = copy.deepcopy(model)
            changed['configurations'][0]['directories'][0]['targetIndexes'] = indexes
            with self.subTest(indexes=indexes), self.assertRaises(shards.EvidenceError):
                collect(text, changed)
        for index in (-1, 99, True):
            changed = copy.deepcopy(model)
            changed['configurations'][0]['targets'][0]['directoryIndex'] = index
            with self.subTest(index=index), self.assertRaises(shards.EvidenceError):
                collect(text, changed)

    def test_directory_paths_hierarchy_and_aliases_must_be_unambiguous(self):
        text, model = fixture()
        mutations = [
            (0, 'build', 'root'), (1, 'build', '.'), (1, 'build', './tests'),
            (1, 'build', '../tests'), (1, 'build', 'tests//alias'),
            (1, 'build', '$(tests)'), (1, 'build', 'tests\\alias'),
            (0, 'childIndexes', []), (0, 'childIndexes', [1, 1]),
            (0, 'childIndexes', [99]), (1, 'parentIndex', 2),
            (1, 'parentIndex', True), (1, 'source', None),
            (0, 'source', 'not-root'), (1, 'build', 'CMakeFiles/engine.dir'),
        ]
        for index, key, value in mutations:
            changed = copy.deepcopy(model)
            changed['configurations'][0]['directories'][index][key] = value
            with self.subTest(index=index, key=key, value=value), \
                    self.assertRaises(shards.EvidenceError):
                collect(text, changed)

    def test_codemodel_shape_version_and_selected_configuration_are_validated(self):
        text, model = fixture()
        changed = copy.deepcopy(model)
        changed['configurations'].append(copy.deepcopy(changed['configurations'][0]))
        variants = [changed, [], {**model, 'kind': 'cache'},
                    {**model, 'version': {'major': 1, 'minor': 0}},
                    {**model, 'version': {'major': True, 'minor': 0}},
                    {**model, 'paths': {'source': None, 'build': '/synthetic/build'}},
                    {**model, 'configurations': []}]
        for changed in variants:
            with self.subTest(model=changed), self.assertRaises(shards.EvidenceError):
                collect(text, changed)

    def test_json_bytes_reject_duplicate_keys_nonfinite_and_invalid_text(self):
        text, _ = fixture()
        for data in (b'{"kind":"codemodel","kind":"cache"}',
                     b'{"value":NaN}', b'{"value":1e999}', b'[]', b'\xff', b'{'):
            with self.subTest(data=data), self.assertRaises(shards.EvidenceError):
                shards.collect_inventory(text.encode(), data, configuration='Release',
                                         head=HEAD, tree=TREE, architecture='synthetic')

    def test_identity_and_architecture_claims_must_have_valid_shape(self):
        for overrides in ({'head': 'short'}, {'tree': 'A' * 40},
                          {'architecture': ''}, {'architecture': 'x86\nall'},
                          {'configuration': ''}):
            with self.subTest(overrides=overrides), self.assertRaises(shards.EvidenceError):
                collect(**overrides)


class InventoryCliTests(unittest.TestCase):
    def setUp(self):
        self.directory = SCRATCH / ('clang-build-inventory-' + uuid.uuid4().hex)
        self.directory.mkdir(parents=True)
        text, model = fixture()
        self.makefile = self.directory / 'Makefile2'
        self.codemodel = self.directory / 'codemodel.json'
        self.makefile.write_text(text, encoding='utf-8')
        self.codemodel.write_bytes(encoded(model))

    def invoke(self, *, makefile=None, codemodel=None, output=None, report=None, stderr=None):
        output = self.directory / (uuid.uuid4().hex + '.json') if output is None else output
        report = self.directory / (uuid.uuid4().hex + '.report.json') if report is None else report
        stderr = io.StringIO() if stderr is None else stderr
        with contextlib.redirect_stderr(stderr):
            code = shards.main([
                'inventory', '--makefile2', str(self.makefile if makefile is None else makefile),
                '--codemodel', str(self.codemodel if codemodel is None else codemodel),
                '--configuration', 'Release', '--head', HEAD, '--tree', TREE,
                '--architecture', 'synthetic-arm64', '--scratch-dir', str(self.directory),
                '--output', str(output), '--report', str(report)])
        return code, output, report, stderr.getvalue()

    def test_cli_lists_inputs_before_opening_and_publishes_the_judged_inventory(self):
        original = Path.read_bytes
        opened = []
        stderr = io.StringIO()

        def audited_read(path):
            audit = stderr.getvalue()
            self.assertIn(str(self.makefile), audit)
            self.assertIn(str(self.codemodel), audit)
            self.assertIn('resolved_inputs', audit)
            opened.append(path)
            return original(path)

        # The actual CLI is called directly: no subprocess or execution wrapper.
        with mock.patch.object(Path, 'read_bytes', audited_read):
            code, output, report, audit = self.invoke(stderr=stderr)
        self.assertEqual(code, 0, audit)
        self.assertEqual(opened, [self.makefile, self.codemodel])
        result = json.loads(output.read_text())
        self.assertEqual(result, collect())
        diagnostic = json.loads(report.read_text())
        self.assertEqual(diagnostic['status'], 'validated')
        self.assertEqual(diagnostic['output_sha256'],
                         hashlib.sha256(output.read_bytes()).hexdigest())

    def test_cli_follows_only_explicit_inputs_never_codemodel_json_references(self):
        text, model = fixture()
        model['configurations'][0]['targets'][0]['jsonFile'] = 'not-present.json'
        self.codemodel.write_bytes(encoded(model))
        original = Path.read_bytes
        opened = []

        def explicit_read(path):
            self.assertIn(path, (self.makefile, self.codemodel))
            opened.append(path)
            return original(path)

        with mock.patch.object(Path, 'read_bytes', explicit_read):
            code, output, _, audit = self.invoke()
        self.assertEqual(code, 0, audit)
        self.assertEqual(opened, [self.makefile, self.codemodel])
        self.assertEqual(json.loads(output.read_text())['targets'], collect(text, model)['targets'])

    def test_cli_bad_graph_publishes_error_report_without_result(self):
        text, _ = fixture()
        self.makefile.write_text(text + 'all: unknown\n', encoding='utf-8')
        code, output, report, _ = self.invoke()
        self.assertNotEqual(code, 0)
        self.assertFalse(output.exists())
        self.assertEqual(json.loads(report.read_text())['status'], 'error')

    def test_cli_inventory_outputs_are_fresh_distinct_and_inside_scratch(self):
        before = self.makefile.read_bytes()
        for output in (self.makefile, self.directory.parent / 'outside-inventory.json'):
            code, _, _, _ = self.invoke(output=output)
            self.assertNotEqual(code, 0)
            self.assertEqual(self.makefile.read_bytes(), before)
        path = self.directory / 'same.json'
        code, _, _, _ = self.invoke(output=path, report=path)
        self.assertNotEqual(code, 0)

    def test_cli_refuses_sensitive_input_names_before_any_input_read(self):
        for name in ('.ssh/key', '.aws/config', '.codex/auth.json', 'secret.env',
                     '.config/zsh/keys/key', '.config/pineforge/state'):
            with self.subTest(name=name), mock.patch.object(
                    Path, 'read_bytes', side_effect=AssertionError('input opened')):
                code, output, _, audit = self.invoke(makefile=self.directory / name)
            self.assertNotEqual(code, 0)
            self.assertFalse(output.exists())
            self.assertIn('refused path', audit)


